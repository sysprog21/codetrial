#!/bin/sh

# Install a wrapper for every scripts/git-*.sh into the repository's hooks
# directory, then check that each is a hook git will run. A worktree shares its
# hooks directory with its siblings, so each wrapper finds the worktree that
# invoked it instead of naming one by path.
#
# Exit 0 means every hook is in effect, not merely that this script ran. --check
# asks the same question without writing anything, and build.rs asks it on every
# build-script rerun.

set -u

mode=install
case "${1:-}" in
    "") ;;
    --check) mode=check ;;
    --uninstall) mode=uninstall ;;
    *)
        echo "usage: ${0##*/} [--check | --uninstall]" >&2
        exit 2
        ;;
esac

ROOT=$(git rev-parse --show-toplevel) || exit 1
cd "$ROOT" || exit 1

# Joined by hand rather than asked for with --path-format=absolute, which git
# before 2.31 echoes back as if it were a path. Both answers are relative to the
# working directory, which is the top level now, except in a linked worktree,
# where they are absolute and Git for Windows starts them with a drive letter.
abs()
{
    case "$1" in
        /* | [A-Za-z]:/*) printf '%s\n' "$1" ;;
        *) printf '%s/%s\n' "$ROOT" "$1" ;;
    esac
}
hooks=$(abs "$(git rev-parse --git-path hooks)") || exit 1
common=$(abs "$(git rev-parse --git-common-dir)") || exit 1

# The wrapper says it is ours on its second line, so a later install can tell it
# from a hook somebody wrote and rewrite it when its text changes, rather than
# having to recognise every version it ever wrote byte for byte. A hook of the
# user's own lives beside it as NAME.local and runs after ours, with the same
# arguments and the same stdin, which pre-push needs because ours reads the refs
# there to the end. Kept in a file rather than a variable, which would drop
# trailing blank lines and invent a final newline. A branch from before the
# scripts existed has no script to run, and committing there is not this hook's
# business. Nor is a merge: by the time its commit-msg or prepare-commit-msg
# fires the incoming tree is written, and running its scripts would make `git
# pull` execute what it pulled.
marker='# Generated by scripts/install-git-hooks.sh; make hooks rewrites it.'
wrapper()
{
    cat << EOF
#!/bin/sh
$marker
top=\$(git rev-parse --show-toplevel) || exit 1
script=\$top/scripts/git-$1.sh
[ -f "\$script" ] || script=/dev/null
[ -f "\$(git rev-parse --git-path MERGE_HEAD)" ] && script=/dev/null
[ -x "\$0.local" ] || exec sh "\$script" "\$@"
input=\$(mktemp) || exit 1
trap 'rm -f "\$input"' EXIT
cat > "\$input"
sh "\$script" "\$@" < "\$input" || exit
"\$0.local" "\$@" < "\$input"
EOF
}

# What the installer wrote before the marker existed, so those wrappers are
# upgraded rather than kept as somebody else's.
legacy()
{
    printf '%s\n' '#!/bin/sh' \
        "exec \"\$(git rev-parse --show-toplevel)/scripts/git-$1.sh\" \"\$@\""
}

ours()
{
    [ -f "$1" ] && ! [ -L "$1" ] && {
        [ "$(sed -n 2p "$1")" = "$marker" ] || legacy "$2" | cmp -s - "$1"
    }
}

current()
{
    wrapper "$2" | cmp -s - "$1"
}

# Where a directory really is, so a symlink inside the repository that leads to
# a shared directory outside it is judged by where it leads. A directory that
# does not exist yet is judged by its parent, which is where mkdir will put it.
real()
{
    if [ -d "$1" ]; then
        (cd -P -- "$1" && pwd -P)
    else
        printf '%s/%s\n' "$(real "$(dirname -- "$1")")" "${1##*/}"
    fi
}

names()
{
    for hook in "$ROOT"/scripts/git-*.sh; do
        name=${hook##*/git-}
        printf '%s\n' "${name%.sh}"
    done
}

# What to do about a hook somebody else wrote: moved beside ours as NAME.local
# it runs after ours, unless a NAME.local is already there, when moving it would
# overwrite one of their two hooks.
foreign()
{
    printf '  FOREIGN %s is not ours and was left in place.\n' "$1" >&2
    if [ -e "$1.local" ]; then
        printf '          %s.local exists too; merge the two into it, remove %s\n' \
            "$2" "$2" >&2
        echo "          and run make hooks again." >&2
    else
        echo "          To run both, ours first with the same arguments and stdin:" >&2
        printf '            mv "%s" "%s.local" && make hooks\n' "$1" "$1" >&2
    fi
}

# Whether every hook is the current wrapper and one git will run. Content is not
# enough: git skips a hook without the executable bit and says nothing, so a
# wrapper that lost it reads as installed while nothing runs.
#
# Progress goes to stdout and anything a person has to act on to stderr, so
# build.rs can pass the second on as it stands and drop the first.
verify()
{
    status=0
    for name in $(names); do
        target=$hooks/$name
        if ! [ -e "$target" ]; then
            printf '  MISSING %s\n' "$target" >&2
        elif ! ours "$target" "$name"; then
            foreign "$target" "$name"
        elif ! current "$target" "$name"; then
            printf '  STALE   %s is an older wrapper\n' "$target" >&2
        elif ! [ -x "$target" ]; then
            printf '  NOEXEC  %s is not executable, so git skips it\n' "$target" >&2
        elif [ -e "$target.local" ] && ! [ -x "$target.local" ]; then
            printf '  NOEXEC  %s.local is not executable, so it never runs\n' "$target" >&2
        else
            printf '  OK      %s%s\n' "$name" \
                "$([ -e "$target.local" ] && echo ", then $name.local")"
            continue
        fi
        status=1
    done
    if [ "$status" -ne 0 ]; then
        echo "Not every hook is in effect in $hooks; run make hooks." >&2
    fi
    return "$status"
}

if [ "$mode" = check ]; then
    verify
    exit
fi

# A hook of the user's that sat behind ours goes back where it came from. Every
# hook in the directory rather than the scripts this checkout has, so a wrapper
# whose script a branch has since removed is not left behind.
if [ "$mode" = uninstall ]; then
    for target in "$hooks"/*; do
        name=${target##*/}
        case "$name" in *.local) continue ;; esac
        ours "$target" "$name" || continue
        rm -f "$target"
        printf '  RM      %s\n' "$name"
        if [ -e "$target.local" ] && mv "$target.local" "$target"; then
            printf '  RESTORE %s\n' "$name"
        fi
    done
    exit 0
fi

# core.hooksPath can send every repository's hooks to one shared directory,
# usually from a global config. Writing there would install these wrappers for
# repositories that have no scripts/ to run, so this only reports.
case "$(real "$hooks")/" in
    "$(real "$common")/"* | "$(real "$ROOT")/"*) ;;
    *)
        cat << EOF >&2
  SHARED  core.hooksPath points hooks at $hooks,
          outside this repository; nothing was written there. To give this
          clone hooks of its own that still run the shared ones after ours:
            git config core.hooksPath "$common/hooks"
            ln -s "$hooks/<name>" "$common/hooks/<name>.local"   # each to keep
          then run make hooks again.
EOF
        verify
        exit
        ;;
esac

# Written beside the target and renamed over it, so a build and a terminal
# installing at once never leave a half-written hook for the other to judge.
write()
{
    wrapper "$1" > "$2.$$" && chmod +x "$2.$$" && mv -f "$2.$$" "$2"
}

mkdir -p "$hooks" || exit 1
for name in $(names); do
    target="$hooks/$name"

    # An existing hook is somebody's: overwriting it is how a local workflow
    # disappears without anyone noticing. It is left alone, and verify below
    # reports it as FOREIGN with what to do about it.
    if ours "$target" "$name"; then
        if ! current "$target" "$name" && write "$name" "$target"; then
            printf '  UPDATE  %s\n' "$name"
        fi
        chmod +x "$target"
    elif ! [ -e "$target" ] && ! [ -L "$target" ] && write "$name" "$target"; then
        printf '  HOOK    %s\n' "$name"
    fi
done

verify
